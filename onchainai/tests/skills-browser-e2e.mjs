// Headless UI e2e for /skills (devnet). BASE=… KEYPAIR=throwaway.json SHOTS=… node tests/skills-browser-e2e.mjs
import { chromium } from 'playwright';
import { readFileSync } from 'node:fs';
import nacl from 'tweetnacl';
import { injectTestWallet } from './_test-wallet.mjs';
const BASE = process.env.BASE || 'http://localhost:4199', SHOTS = process.env.SHOTS || '/workspace/hf-mint-shots';
const kp = nacl.sign.keyPair.fromSecretKey(Uint8Array.from(JSON.parse(readFileSync(process.env.KEYPAIR, 'utf8'))));
const browser = await chromium.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on('pageerror', e => console.error('pageerror', e.message));
await injectTestWallet(page, kp);
await page.goto(`${BASE}/skills`, { waitUntil: 'networkidle' });
await page.screenshot({ path: `${SHOTS}/10-skillhub-hero.png` });
await page.click('#submit-btn');
await page.waitForSelector('#verdict:not([hidden])', { timeout: 60000 });
await page.evaluate(() => document.getElementById('verdict').scrollIntoView({ block: 'start' }));
await page.waitForTimeout(300);
await page.screenshot({ path: `${SHOTS}/11-skillhub-verdict.png` });
await page.$eval('#s-wallet-btn', b => b.click());
await page.click('#wallet-dialog button:has-text("Devnet Test Wallet")');
await page.$eval('#s-bind-btn', b => b.click());
await page.waitForSelector('#s-bind-status.ok');
await page.$eval('#s-mint-btn', b => b.click());
await page.waitForSelector('#s-result:not([hidden]), #s-mint-status.err', { timeout: 90000 });
const err = await page.$('#s-mint-status.err');
if (err) { console.error('mint error', await err.textContent()); process.exit(1); }
const asset = await page.$eval('#s-result .kv .mono', n => n.textContent);
await page.evaluate(() => document.getElementById('mint').scrollIntoView({ block: 'start' }));
await page.screenshot({ path: `${SHOTS}/12-skillhub-minted.png` });
await page.waitForTimeout(10000);
await page.goto(`${BASE}/skills?asset=${asset}`, { waitUntil: 'networkidle' });
await page.waitForSelector('#detail h2', { timeout: 30000 });
await page.evaluate(() => document.getElementById('detail').scrollIntoView({ block: 'start' }));
await page.waitForTimeout(400);
await page.screenshot({ path: `${SHOTS}/13-skill-detail.png` });
await page.evaluate(() => document.getElementById('hub').scrollIntoView({ block: 'start' }));
await page.waitForTimeout(400);
await page.screenshot({ path: `${SHOTS}/14-skillhub-gallery.png` });
console.log(JSON.stringify({ ok: true, asset, detail: await page.$eval('#detail h2', n => n.textContent) }));
await browser.close();
